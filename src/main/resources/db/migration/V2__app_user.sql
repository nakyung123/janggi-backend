-- 로그인한 사람 한 명이 한 줄이다.
--
-- **이름도 이메일도 사진도 두지 않는다.** 구글이 주는 것 중 `sub`(그 사람을 가리키는
-- 번호) 하나만 적는다. 화면에 보여 줄 데가 없고 - `로그인됨` 으로 충분하다 - 두지
-- 않으면 **DB 가 새도 이메일이 안 샌다.** 가지고 있지 않은 것은 잃을 수도 없다.

CREATE TABLE app_user (
    -- event 표와 같은 방식이다. BIGSERIAL 이 아니라 IDENTITY - 표준이고 시퀀스 권한이
    -- 따로 놀지 않는다.
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 구글이 이 사람을 가리키는 번호. **255 ASCII 가 구글이 문서로 못 박은 상한이다**
    -- (지금 실제로 오는 값은 21자리 숫자지만, 늘어나도 괜찮다고 적혀 있는 쪽을 따른다).
    --
    -- 길이를 짐작해서 짧게 잡으면 **나중에 들어온 사람만 조용히 잘린다** - 그 사람은
    -- 다음 로그인 때 남의 계정에 들어갈 수도 있다. 넉넉하게 두는 값이 거의 없다.
    google_sub  VARCHAR(255) NOT NULL UNIQUE,

    -- **이미 내준 쿠키를 한 번에 무효로 만드는 손잡이.**
    --
    -- 쿠키에 (id, token_epoch) 를 같이 담고, 들어올 때 이 값과 맞는지 본다. 탈퇴하거나
    -- 되살릴 때 이 숫자를 올리면 그 전에 내준 쿠키가 전부 못 쓰게 된다.
    --
    -- **왜 이 방식인가** - 내준 토큰을 따로 적어 두는 표를 만들면 요청마다 그 표를
    -- 읽어야 한다. DB 가 싱가포르에 있어서 **한 번 읽는 데 155ms**(재 봤다)다. 이
    -- 숫자는 어차피 하는 질의에 조건으로 얹을 수 있어서 왕복이 늘지 않는다.
    token_epoch INT          NOT NULL DEFAULT 1,

    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- 탈퇴한 때. **줄을 바로 지우지 않는다** - 실수로 눌렀을 때 30일 안에 다시
    -- 로그인하면 기보가 그대로 돌아온다.
    --
    -- **이 칸과 위의 UNIQUE 가 부딪힌다.** 탈퇴해도 줄이 남아 있으니 `google_sub` 가
    -- 계속 묶여 있고, 30일이 지났어도 **지우개가 돌기 전에 다시 로그인하면 INSERT 가
    -- 유일 제약에 걸린다.** 그래서 로그인은 한 문장이 아니라 두 문장이다 - 만료된 것을
    -- 먼저 치우고, 그다음에 넣거나 되살린다. 까닭은 `GAMES.md` 의 "로그인 - 두 문장으로
    -- 네 경우" 에 표로 있다.
    deleted_at  TIMESTAMPTZ
);

-- **인덱스를 더 만들지 않는다.**
--
-- `google_sub` 의 UNIQUE 가 인덱스라서 로그인 조회는 그것으로 끝나고, 나머지 질의는
-- 전부 `id` 로 찾는다. 30일 지난 것을 치우는 일만 `deleted_at` 을 훑는데, 그건 하루
-- 한 번 돌고 줄 수가 사람 수만큼이다 - 인덱스를 얹는 값이 아끼는 값보다 크다.
--
-- event 표에서 쓴 기준과 같다. **실제로 느려지면** 그때 재고 넣는다.
