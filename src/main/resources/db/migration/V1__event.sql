-- 사용 기록 한 건이 한 줄이다.
--
-- **세션 표를 따로 두지 않았다.** 기기 정보(browser·os·screen…)가 줄마다 되풀이되지만,
-- 세션 표를 만들면 "있나 보고 나서 쓴다"가 되고 그 읽고-쓰기 사이가 바로 중복과 경쟁이
-- 사는 자리다. 게다가 우리는 세션이 **언제 끝나는지 영영 모른다** - 떠나는 것을 못 본다.
-- 아끼는 용량은 하루 5KB 쯤이라 바꿀 값이 못 된다. 더하기만 하는 표가 수집기에서 제일
-- 안전하다.

CREATE TABLE event (
    -- BIGSERIAL 이 아니라 IDENTITY 다. 표준이고, 시퀀스 권한이 따로 놀지 않는다.
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- **기준은 받은 시각이다.** 보낸 쪽 시각(sent_at)은 사용자 시계가 틀릴 수 있어 참고용.
    -- TIMESTAMPTZ 를 쓴다 - 시간대 없는 타입에 UTC 를 넣어 두면 나중에 누가 지역 시각으로
    -- 읽는다.
    received_at TIMESTAMPTZ NOT NULL,

    name        VARCHAR(32) NOT NULL,
    sid         VARCHAR(16) NOT NULL,
    sent_at     BIGINT,

    env         VARCHAR(8),
    ver         VARCHAR(16),
    browser     VARCHAR(64),
    os          VARCHAR(32),
    in_app      VARCHAR(32),
    isolated    BOOLEAN,
    cores       SMALLINT,
    memory      SMALLINT,
    screen      VARCHAR(16),

    -- 이벤트마다 모양이 다른 칸. 자주 바뀔 자리라 한 칸에 몰아 둔다.
    data        JSONB
);

-- 같은 것이 두 번 들어오는 것을 막는다.
--
-- **왜 필요한가** - `navigator.sendBeacon` 은 at-least-once 다. 망이 끊기면 브라우저가
-- **묶음을 통째로 다시 보낸다.** 그러면 세 칸이 전부 같은 줄이 또 온다.
--
-- **왜 이 세 칸인가** - 2026-10-11 로그의 진짜 사용자 37건에서 (sid, name, sent_at) 이
-- 겹치는 것이 0건이었다. 같은 세션에서 같은 이름이 여러 번 나오긴 하지만(한 판 더 두면
-- first_move 가 또 찍힌다) 보낸 시각이 달라서 갈린다.
--
-- **sent_at 이 비는 줄은 안 걸러진다.** Postgres 는 NULL 끼리 같다고 보지 않기 때문이다.
-- 비는 것은 전부 내가 돌린 curl·CI 시험이고(브라우저는 항상 보낸다), 그것들은 걸러질
-- 까닭이 없어서 마침 잘 맞는다.
CREATE UNIQUE INDEX event_once_idx ON event (sid, name, sent_at);

-- 모든 질문이 "언제부터 언제까지"로 시작한다.
--
-- **다른 인덱스를 안 만든 까닭** - 하루 80줄이면 일 년에 3만 줄이고, 그 크기에서는
-- Postgres 가 통째로 훑어도 빠르다. 인덱스는 넣을 때마다 값을 치르고 자리를 먹는데 무료
-- 저장이 1GB 다. **실제로 느려지면** 그때 재고 넣는다.
CREATE INDEX event_received_at_idx ON event (received_at DESC);
