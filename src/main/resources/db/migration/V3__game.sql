-- 끝난 판 하나가 한 줄이다.
--
-- **수를 따로 표로 쪼개지 않는다.** 처음 설계에는 `game_move(game_id, ply, move, grade)` 가
-- 있었는데, 프런트의 실제 모양을 읽고 접었다.
--
--     HistoryEntry  { fen, move, notation, mover, score }   <- 수마다 FEN 이 하나씩
--     ReviewedMove  { index, mover, played, playedNotation, playedPlain?, ... }
--
-- 쪼개도 **바이트가 줄지 않는다** - FEN 을 어차피 줄마다 적어야 한다. 대신 조인이 생기고,
-- "100수 기보를 80수로 다시 올리면 81~100수가 남는" 버그를 막는 일이 생긴다. 한 줄에
-- 담으면 그 버그가 **생길 구조가 아니다.**
--
-- **수 안을 뒤지는 기능이 없다.** 목록은 요약만 보여 주고, 한 판을 열면 통째로 쓴다.
-- 쪼개서 얻는 것이 질의인데 그 질의를 할 데가 없다.
--
-- **FEN 을 버리고 브라우저가 다시 둬서 만드는 길은 안 갔다.** 바이트는 80% 줄지만,
-- 규칙이 바뀌면 옛 기보가 조용히 다른 판으로 보인다. 끝난 판은 그때 모습 그대로여야 한다.

CREATE TABLE game (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 계정이 지워지면 기보도 같이 간다. 30일 지난 탈퇴를 치우는 일이 이 한 줄에 업혀 있다.
    user_id        BIGINT      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,

    -- 브라우저가 만든 번호(`newGameId`: 36진수 시각 + '-' + 36진수 4자).
    --
    -- **내용 해시를 쓰지 않는 까닭** - 짧은 판에서 충돌한다. 실서버에 `2수 · 초 기권패`
    -- 기보가 있고, 수순만으로 해시를 내면 다른 두 판이 한 줄로 합쳐진다.
    --
    -- **전역 식별자가 아니다.** 다른 기기에서 같은 대국을 올리면 두 줄이 된다 - 기기마다
    -- 번호를 따로 만들기 때문이고, 그게 맞는 동작이다.
    client_game_id VARCHAR(24) NOT NULL,

    -- 판이 끝난 때. **브라우저 시각이다.** 목록이 이 순서로 선다.
    ended_at       TIMESTAMPTZ NOT NULL,

    my_side        VARCHAR(4)  NOT NULL,   -- cho | han
    level_id       VARCHAR(16) NOT NULL,   -- k18 … 급수 사다리가 바뀌어도 그때 것으로 남는다
    level_name     VARCHAR(32) NOT NULL,   -- 18급
    variant        VARCHAR(32) NOT NULL,

    -- checkmate · stalemate · points · bikjang · passes · resign · flag · record · abandoned
    result_kind    VARCHAR(16) NOT NULL,
    -- 이긴 쪽. 비겼거나 안 끝났으면 비운다.
    result_winner  VARCHAR(4),

    -- **목록에 쓰려고 따로 둔다.** history 의 길이에서 나오는 값이지만, 목록을 그릴 때
    -- jsonb 를 열어 세면 블롭을 전부 읽어야 한다 - 목록이 수십 줄이면 그게 수백 KB다.
    moves_count    SMALLINT    NOT NULL,

    -- 국면마다 FEN · 수 · 기보 표기 · 둔 쪽 · 평가치. 한 판이 100수면 4만 자쯤이다.
    history        JSONB       NOT NULL,
    -- 복기를 돌렸으면 그 결과. 안 돌렸으면 비운다.
    --
    -- **모양을 서버가 못 박지 않는다.** `ReviewedMove.playedPlain` 주석에 "예전 복기에는
    -- 없어서 물음표를 붙인다" 고 적혀 있다 - 이미 한 번 칸이 는 자리다. 못 박으면 프런트가
    -- 칸을 더하는 날 **서버가 조용히 버린다**(잭슨 기본값이 모르는 칸을 버린다).
    reviewed       JSONB,

    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),   -- 처음 올라온 때
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),   -- 덮어쓴 때

    -- **이 제약이 설계의 열쇠다.** 한 판이 여러 번 올라온다 - 끝나는 순간, 복기를 돌린 뒤,
    -- 무르고 다시 둔 뒤. `archive.ts` 도 "같은 id 가 있으면 바꾼다" 로 되어 있고 서버가
    -- 같은 규칙을 쓴다. `/events` 의 `(sid, name, sent_at)` 과 같은 방식이다.
    --
    -- **ON CONFLICT DO NOTHING 으로 하면 안 된다** - 두 번째를 무시하므로 복기 등급이
    -- 영원히 안 들어온다.
    UNIQUE (user_id, client_game_id)
);

-- 목록은 늘 "내 것, 끝난 순서" 다.
--
-- `id` 를 뒤에 붙인 까닭 - 같은 밀리초에 끝난 두 판이 있어도 순서가 흔들리지 않는다.
-- 커서 페이징이 생기면 그때도 이 순서를 그대로 쓴다.
CREATE INDEX game_list_idx ON game (user_id, ended_at DESC, id DESC);
